# Histogram support
# ==============================================================================

def percentile(values, pct):
    """
    Return an interpolated percentile.
    values must be non-empty.
    """
    data = sorted(values)

    if len(data) == 1:
        return data[0]

    position = (len(data) - 1) * pct
    low = int(math.floor(position))
    high = int(math.ceil(position))

    if low == high:
        return data[low]

    fraction = position - low

    return data[low] + fraction * (data[high] - data[low])


def choose_histogram_bin_width(values):
    """
    Choose a histogram bin width using the Freedman-Diaconis rule,
    with limits to avoid an unreasonable number of bins.
    """
    if len(values) < 2:
        return 0.1

    minimum = min(values)
    maximum = max(values)
    data_range = maximum - minimum

    if data_range <= 0:
        return 0.1

    q1 = percentile(values, 0.25)
    q3 = percentile(values, 0.75)
    iqr = q3 - q1

    if iqr > 0:
        bin_width = 2.0 * iqr / (len(values) ** (1.0 / 3.0))
    else:
        # Fall back to about 20 bins if the distribution
        # has little or no interquartile range.
        bin_width = data_range / 20.0

    # Limit the histogram to no more than about 100 bins
    # and no fewer than about 5 bins.
    minimum_width = data_range / 100.0
    maximum_width = data_range / 5.0

    if minimum_width > 0:
        bin_width = max(bin_width, minimum_width)

    if maximum_width > 0:
        bin_width = min(bin_width, maximum_width)

    # No need for extremely fine timing bins.
    bin_width = max(bin_width, 0.01)

    return bin_width


def build_histogram(values):
    """
    Return:
        bin_edges
        bin_centers
        counts
    """
    if not values:
        return [], [], []

    minimum = min(values)
    maximum = max(values)

    if minimum == maximum:
        width = max(0.01, minimum * 0.01)

        return (
            [minimum - width / 2.0, minimum + width / 2.0],
            [minimum],
            [len(values)]
        )

    width = choose_histogram_bin_width(values)

    start = math.floor(minimum / width) * width
    end = math.ceil(maximum / width) * width

    bin_count = max(
        1,
        int(math.ceil((end - start) / width))
    )

    edges = [
        start + i * width
        for i in range(bin_count + 1)
    ]

    counts = [0] * bin_count

    for value in values:

        index = int((value - start) / width)

        if index >= bin_count:
            index = bin_count - 1

        if index < 0:
            index = 0

        counts[index] += 1

    centers = [
        (edges[i] + edges[i + 1]) / 2.0
        for i in range(bin_count)
    ]

    return edges, centers, counts


def transform_histogram_count(count, y_scale):
    """
    Transform histogram population for display.
    """
    if y_scale == "log":
        return math.log10(count + 1.0)

    return float(count)


def print_ascii_histogram(centers, counts, y_scale):
    """
    Display a rough histogram on the console.
    """
    if not counts:
        return

    print()
    print("Deployment timing histogram:")
    print("Y-axis: " + y_scale)
    print()

    graph_width = 50

    transformed = [
        transform_histogram_count(count, y_scale)
        for count in counts
    ]

    maximum = max(transformed)

    if maximum <= 0:
        maximum = 1.0

    for center, count, transformed_value in zip(
            centers,
            counts,
            transformed
    ):

        if count == 0:
            bar_length = 0
        else:
            bar_length = max(
                1,
                int(round(
                    graph_width
                    * transformed_value
                    / maximum
                ))
            )

        print(
            f"{center:8.3f} s | "
            f"{'#' * bar_length:<50} "
            f"{count:6d}"
        )


# ==============================================================================
# Timing population analysis
# ==============================================================================

def find_timing_populations(values, edges, counts):
    """
    Find separated timing populations in the histogram.

    A timing population begins at a non-empty histogram bin and continues
    until MIN_EMPTY_BINS_BETWEEN_POPULATIONS consecutive empty bins have
    been encountered.  One isolated empty bin is therefore allowed inside
    a population.

    Every population is retained, including populations containing only
    one timing sample.  Statistics are calculated from the original timing
    measurements, not from histogram-bin centers.

    Returns dictionaries containing:
        mean
        stdev
        count
        percent

    sorted by increasing timing.
    """
    if not values or not counts or len(edges) < 2:
        return []

    population_ranges = []
    start_index = None
    last_nonzero_index = None
    empty_run = 0

    # --------------------------------------------------------------------------
    # Identify separated islands of occupied histogram bins.
    # --------------------------------------------------------------------------

    for index, count in enumerate(counts):

        if count > 0:

            if start_index is None:
                start_index = index

            last_nonzero_index = index
            empty_run = 0

        elif start_index is not None:

            empty_run += 1

            if empty_run >= MIN_EMPTY_BINS_BETWEEN_POPULATIONS:

                population_ranges.append(
                    (
                        start_index,
                        last_nonzero_index
                    )
                )

                start_index = None
                last_nonzero_index = None
                empty_run = 0

    # A population can extend through the final histogram bin.
    if start_index is not None:

        population_ranges.append(
            (
                start_index,
                last_nonzero_index
            )
        )

    # --------------------------------------------------------------------------
    # Map each histogram bin to its population.
    # --------------------------------------------------------------------------

    bin_to_population = [None] * len(counts)

    for population_index, (first_bin, last_bin) in enumerate(
            population_ranges
    ):

        for bin_index in range(first_bin, last_bin + 1):
            bin_to_population[bin_index] = population_index

    groups = [
        []
        for _ in population_ranges
    ]

    bin_width = edges[1] - edges[0]

    # --------------------------------------------------------------------------
    # Assign each original timing measurement to its histogram population.
    # --------------------------------------------------------------------------

    for value in values:

        bin_index = int(
            (value - edges[0])
            / bin_width
        )

        if bin_index < 0:
            bin_index = 0

        if bin_index >= len(counts):
            bin_index = len(counts) - 1

        population_index = bin_to_population[bin_index]

        if population_index is not None:
            groups[population_index].append(value)

    # --------------------------------------------------------------------------
    # Calculate statistics from the original timing values.
    # --------------------------------------------------------------------------

    total = len(values)
    populations = []

    for group in groups:

        if not group:
            continue

        mean = statistics.mean(group)

        if len(group) >= 2:
            deviation = statistics.stdev(group)
        else:
            deviation = 0.0

        populations.append(
            {
                "mean": mean,
                "stdev": deviation,
                "count": len(group),
                "percent": (
                    100.0
                    * len(group)
                    / total
                ),
            }
        )

    populations.sort(
        key=lambda item: item["mean"]
    )

    return populations


def report_deployment_timings(values, y_scale):
    """
    Display histogram and numerical timing results.
    """
    print()
    print("============================================================")
    print("Deployment timing analysis")
    print("============================================================")

    if not values:
        print("No successful deployment timing measurements.")
        return

    edges, centers, counts = build_histogram(values)

    # --------------------------------------------------------------------------
    # Histogram first.
    # --------------------------------------------------------------------------

    print_ascii_histogram(
        centers,
        counts,
        y_scale
    )

    # --------------------------------------------------------------------------
    # Overall numerical information.
    # --------------------------------------------------------------------------

    mean = statistics.mean(values)

    if len(values) >= 2:
        stdev = statistics.stdev(values)
    else:
        stdev = 0.0

    print()
    print("Deployment timing statistics:")
    print()
    print(f"Successful timed deployments: {len(values)}")
    print(f"Minimum:                      {min(values):.3f} sec")
    print(f"Maximum:                      {max(values):.3f} sec")
    print(f"Overall mean:                 {mean:.3f} sec")
    print(f"Overall standard deviation:   {stdev:.3f} sec")

    # --------------------------------------------------------------------------
    # Timing populations.
    # --------------------------------------------------------------------------

    populations = find_timing_populations(
        values,
        edges,
        counts
    )

    if populations:

        print()
        print("Timing populations:")
        print()
        print(
            "     Timing                 Population       Percent"
        )
        print(
            "  -------------------       ----------       -------"
        )

        for population in populations:

            print(
                f"  "
                f"{population['mean']:7.3f} +/- "
                f"{population['stdev']:6.3f} sec"
                f"       "
                f"{population['count']:6d}"
                f"          "
                f"{population['percent']:6.2f}%"
            )



# ==============================================================================
# One complete test
# ==============================================================================

def test_the_situation(bitwise_ip, channel, file_name):
    """
    Perform one Pela pattern deployment test.

    The first Deploy() attempt is timed.  If it fails, the same deployment is
    attempted a second time without restarting the timer.  A timing sample is
    retained if either attempt succeeds.  If both attempts fail, no timing
    sample is recorded.

    Returns:
        first_deploy_success
        second_deploy_success
        deploy_elapsed
        failure_events
        ed_data_rate
        temperature_c

    Returns None if the test cannot be started/completed because of a
    connection or other non-Deploy automation error.
    """

    first_deploy_success = True
    second_deploy_success = True
    deploy_elapsed = None
    failure_events = []
    ed_data_rate = None
    temperature_c = None

    Pela = PelaDevice()
    connected = False

    try:
        if DEBUG_FLAG:
            Pela.setDebugging(True)

        Pela.Connect(bitwise_ip)
        connected = True

        serial_number = Pela.Const.getSN()
        ed_data_rate = Pela.ED.getDataRateGHz()
        temperature_c = Pela.getTemperatureC()

        if VERBOSE_FLAG:
            print(
                "Device connected : IP ADDRESS : "
                + str(bitwise_ip)
            )
            print(
                "Device connected : Serial ID  : "
                + str(serial_number)
            )
            print(
                "ED Data Rate: "
                + str(ed_data_rate)
                + " Gbps"
            )
            print(
                "Temperature: "
                + f"{temperature_c:.2f} C"
            )
            print(
                "Channel: "
                + channel.name
            )
            print(
                "Pattern file: "
                + file_name
            )

        # Preserve the short settling delay used by TestPelaDeploy.py,
        # but do not include it in the deployment timing measurement.
        time.sleep(0.5)

        deploy_start = time.perf_counter()

        try:
            Pela.Patt.Deploy(
                channel,
                file_name,
                0
            )

            deploy_elapsed = (
                time.perf_counter()
                - deploy_start
            )

        except Exception as e:
            first_deploy_success = False

            failure_events.append(
                (
                    "First Deploy",
                    datetime.now().strftime("%Y-%m-%d %H:%M:%S")
                )
            )

            print(str(e))
            print("First Deploy ERROR")

            try:
                Pela.Patt.Deploy(
                    channel,
                    file_name,
                    0
                )

                # Timer deliberately includes the failed first attempt.
                deploy_elapsed = (
                    time.perf_counter()
                    - deploy_start
                )

            except Exception as e:
                second_deploy_success = False

                failure_events.append(
                    (
                        "Second Deploy",
                        datetime.now().strftime("%Y-%m-%d %H:%M:%S")
                    )
                )

                print(str(e))
                print("Second Deploy ERROR")

                deploy_elapsed = None

        return (
            first_deploy_success,
            second_deploy_success,
            deploy_elapsed,
            failure_events,
            ed_data_rate,
            temperature_c
        )

    except Exception as e:
        print(
            "ERROR: "
            + str(e)
        )
        return None

    finally:
        if connected:
            try:
                Pela.Disconnect()
            except Exception as e:
                print(
                    "ERROR disconnecting Pela: "
                    + str(e)
                )


# ==============================================================================
# Command-line processing
# ==============================================================================

def parse_arguments():
    parser = argparse.ArgumentParser(
        description=(
            "Repeated Pela user-pattern deployment test. "
            "Alternates between two pattern files and runs until Ctrl-C."
        )
    )

    parser.add_argument(
        "ip_address",
        help="IP address of the Pela device"
    )

    parser.add_argument(
        "-prbs",
        "--prbs",
        action="store_true",
        help=(
            "Alternate PRBS files instead of 1100.patt and 10.patt"
        )
    )

    parser.add_argument(
        "-ch",
        "--channel",
        action="append",
        type=int,
        choices=(0, 1),
        help=(
            "Channel to test (0 or 1). May be specified more than once. "
            "Default: channel 0"
        )
    )

    parser.add_argument(
        "-hist",
        "--hist",
        choices=("log", "linear"),
        default="log",
        help="Histogram Y-axis scaling (default: log)"
    )

    parser.add_argument(
        "-verbose",
        "--verbose",
        action="store_true",
        help="Display connection, loop, file and timing information"
    )

    parser.add_argument(
        "-debug",
        "--debug",
        action="store_true",
        help="Enable Pela automation debugging"
    )

    return parser.parse_args()


def make_channels(channel_numbers):
    if not channel_numbers:
        channel_numbers = [0]

    channels = []

    for channel_number in channel_numbers:
        if channel_number == 0:
            channels.append(
                BranchPatt.PatternChannel.Ch0
            )
        else:
            channels.append(
                BranchPatt.PatternChannel.Ch1
            )

    return channels


# ==============================================================================
# Main
# ==============================================================================

if __name__ == '__main__':
    args = parse_arguments()

    DEBUG_FLAG = args.debug
    VERBOSE_FLAG = args.verbose
    HISTOGRAM_Y_SCALE = args.hist

    ip = args.ip_address
    channels = make_channels(args.channel)

    if args.prbs:
        file_names = PRBS_FILE_NAMES
    else:
        file_names = STANDARD_FILE_NAMES

    # Use the Cartesian product so that, when both channels are selected,
    # each channel sees both alternating files rather than permanently pairing
    # one channel with one file.
    test_cases = [
        (channel, file_name)
        for channel in channels
        for file_name in file_names
    ]

    print("PelaDeployLoop")
    print()
    print("Configuration:")
    print(
        "  IP Address:              "
        + ip
    )
    print(
        "  Channels:                "
        + ", ".join(channel.name for channel in channels)
    )
    print(
        "  Pattern files:           "
        + ", ".join(file_names)
    )
    print(
        "  PRBS mode:               "
        + str(args.prbs)
    )
    print(
        "  Verbose:                 "
        + str(VERBOSE_FLAG)
    )
    print(
        "  Debug:                   "
        + str(DEBUG_FLAG)
    )
    print(
        "  Histogram Y-axis:        "
        + HISTOGRAM_Y_SCALE
    )
    print()
    print("Press Ctrl-C to stop.")
    print()

    total_tests = 0
    first_deploy_failures = 0
    second_deploy_failures = 0

    # One elapsed-time measurement for every deployment that eventually
    # succeeded.
    deployment_timings = []

    # Entries:
    #   (test_number, channel_name, file_name, attempt_name, local_time)
    failure_events = []

    start_time = time.perf_counter()

    try:
        while True:
            channel, file_name = test_cases[
                total_tests % len(test_cases)
            ]

            result = test_the_situation(
                ip,
                channel,
                file_name
            )

            # A non-deployment automation/connection failure stops the test,
            # matching TestPegaDeployLoop.py behavior.
            if result is None:
                break

            (
                first_success,
                second_success,
                deploy_elapsed,
                test_failure_events,
                ed_data_rate,
                temperature_c
            ) = result

            total_tests += 1

            if not first_success:
                first_deploy_failures += 1

            if not second_success:
                second_deploy_failures += 1

            for attempt_name, failure_time in test_failure_events:
                failure_events.append(
                    (
                        total_tests,
                        channel.name,
                        file_name,
                        attempt_name,
                        failure_time
                    )
                )

            if deploy_elapsed is not None:
                deployment_timings.append(
                    deploy_elapsed
                )

            if VERBOSE_FLAG:
                elapsed = (
                    time.perf_counter()
                    - start_time
                )

                hours = int(
                    elapsed // 3600
                )
                minutes = int(
                    (elapsed % 3600) // 60
                )
                seconds = elapsed % 60

                if deploy_elapsed is None:
                    timing_text = "FAILED"
                else:
                    timing_text = f"{deploy_elapsed:.3f} sec"

                print(
                    f"Test: {total_tests}   "
                    f"Channel: {channel.name}   "
                    f"File: {os.path.basename(file_name)}   "
                    f"Deploy: {timing_text}"
                )
                print(
                    f"First failures: "
                    f"{first_deploy_failures}   "
                    f"Second failures: "
                    f"{second_deploy_failures}   "
                    f"Timed: "
                    f"{len(deployment_timings)}   "
                    f"Elapsed: "
                    f"{hours:02d}:"
                    f"{minutes:02d}:"
                    f"{seconds:05.2f}"
                )

                if ed_data_rate is not None:
                    print(
                        "ED Data Rate: "
                        + str(ed_data_rate)
                        + " Gbps"
                    )

                if temperature_c is not None:
                    print(
                        "Temperature: "
                        + f"{temperature_c:.2f} C"
                    )

                print()

    except KeyboardInterrupt:
        print(
            "\nCtrl-C encountered"
        )

    elapsed = (
        time.perf_counter()
        - start_time
    )

    hours = int(
        elapsed // 3600
    )
    minutes = int(
        (elapsed % 3600) // 60
    )
    seconds = elapsed % 60

    print()
    print("Final results:")
    print(
        f"Tests completed:        "
        f"{total_tests}"
    )
    print(
        f"First Deploy failures:  "
        f"{first_deploy_failures}"
    )
    print(
        f"Second Deploy failures: "
        f"{second_deploy_failures}"
    )
    print(
        f"Timed deployments:      "
        f"{len(deployment_timings)}"
    )
    print(
        f"Elapsed time:           "
        f"{hours:02d}:"
        f"{minutes:02d}:"
        f"{seconds:05.2f}"
    )

    if failure_events:
        print()
        print("Deployment failure times:")
        print()
        print(
            "  Test    Ch   File                 "
            "Attempt          Local date/time"
        )
        print(
            "  ------  ---  -------------------  "
            "---------------  -------------------"
        )

        for (
                test_number,
                channel_name,
                file_name,
                attempt_name,
                failure_time
        ) in failure_events:
            print(
                f"  {test_number:6d}  "
                f"{channel_name:<3}  "
                f"{os.path.basename(file_name):<19}  "
                f"{attempt_name:<15}  "
                f"{failure_time}"
            )

    report_deployment_timings(
        deployment_timings,
        HISTOGRAM_Y_SCALE
    )


